// Copies the bike-share example workflows (examples/bikeshare) into src/demo/docs.ts and records their workflow
// hashes, so the scripted daemon shows the real documents and the hashes the ogun CLI prints for them.
//
//   node scripts/sync-sample-docs.mjs            # uses target/debug/ogun if it is built, else the recorded hashes
//   OGUN_BIN=/path/to/ogun node scripts/sync-sample-docs.mjs

import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repo = resolve(here, '../../../..')
const out = resolve(here, '../src/demo/docs.ts')

const FILES = {
  'dock-telemetry@1': 'examples/bikeshare/dock-telemetry.workflow.json',
  'trips-backfill@1': 'examples/bikeshare/trips-backfill.workflow.json',
  'rebalance-plan@1': 'examples/bikeshare/rebalance-plan.workflow.json',
  'rebalance-plan@2': 'examples/bikeshare/rebalance-plan.v2.workflow.json',
  'district-report@1': 'examples/bikeshare/district-report.workflow.json',
  'ridership-forecast@1': 'examples/bikeshare/ridership-forecast.workflow.json',
}

let previous = {}
if (existsSync(out)) {
  const m = readFileSync(out, 'utf8').match(/export const HASHES: Record<string, string> = (\{[\s\S]*?\n\})/)
  if (m) previous = JSON.parse(m[1])
}

const candidates = [process.env.OGUN_BIN, resolve(repo, 'target/debug/ogun.exe'), resolve(repo, 'target/debug/ogun')]
const bin = candidates.find((p) => p && existsSync(p))
if (!bin) console.warn('ogun CLI not found; keeping the recorded hashes (build with `cargo build -p ogun-cli`)')

const docs = {}
const hashes = {}
for (const [key, rel] of Object.entries(FILES)) {
  const file = resolve(repo, rel)
  docs[key] = JSON.parse(readFileSync(file, 'utf8'))
  let hash = previous[key]
  if (bin) {
    const printed = execFileSync(bin, ['hash', file], { encoding: 'utf8' }).trim().split(/\s+/).pop()
    if (!/^[0-9a-f]{64}$/.test(printed)) throw new Error(`unexpected output of ogun hash for ${rel}: ${printed}`)
    hash = printed
  }
  if (!hash) throw new Error(`no hash for ${key}: build the CLI or set OGUN_BIN`)
  hashes[key] = hash
}

const header = `// Generated by scripts/sync-sample-docs.mjs from the example workflows in the repository root; do not edit.
// The hashes are what \`ogun hash\` printed for these files${bin ? '' : ' (recorded earlier)'}.

import type { WorkflowDoc } from '../api/types'

`
writeFileSync(
  out,
  header +
    `export const DOCS: Record<string, WorkflowDoc> = ${JSON.stringify(docs, null, 2)}\n\n` +
    `export const HASHES: Record<string, string> = ${JSON.stringify(hashes, null, 2)}\n`,
)
console.log(`wrote ${out} (${Object.keys(docs).length} documents, hashes from ${bin ? bin : 'the previous file'})`)
